-- 짹로그 1단계 스키마. PostgreSQL과 테스트용 H2 둘 다에서 돌아가는 문법만 쓴다.

CREATE TABLE users (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    handle      VARCHAR(20)  NOT NULL,
    nickname    VARCHAR(20)  NOT NULL,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_users_handle UNIQUE (handle)
);

CREATE TABLE parrots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id     BIGINT       NOT NULL REFERENCES users (id),
    name         VARCHAR(20)  NOT NULL,
    species      VARCHAR(30)  NOT NULL,
    birth_date   DATE,
    adopted_date DATE,
    color_face   VARCHAR(7)   NOT NULL,
    color_head   VARCHAR(7)   NOT NULL,
    color_body   VARCHAR(7)   NOT NULL,
    color_wing   VARCHAR(7)   NOT NULL,
    color_tail   VARCHAR(7)   NOT NULL,
    created_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_parrots_owner ON parrots (owner_id);

CREATE TABLE posts (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id     BIGINT        NOT NULL REFERENCES users (id),
    parrot_id     BIGINT        REFERENCES parrots (id),
    body          VARCHAR(2000) NOT NULL,
    weight_g      NUMERIC(5, 1),
    mood          VARCHAR(20),
    like_count    INTEGER       NOT NULL DEFAULT 0,
    comment_count INTEGER       NOT NULL DEFAULT 0,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_posts_author ON posts (author_id, id);

CREATE TABLE post_images (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id   BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    path      VARCHAR(200) NOT NULL,
    width     INTEGER      NOT NULL,
    height    INTEGER      NOT NULL,
    position  INTEGER      NOT NULL
);
CREATE INDEX idx_post_images_post ON post_images (post_id, position);

CREATE TABLE post_likes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    user_id    BIGINT NOT NULL REFERENCES users (id),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_post_likes UNIQUE (post_id, user_id)
);
CREATE INDEX idx_post_likes_user ON post_likes (user_id);

CREATE TABLE comments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    author_id  BIGINT       NOT NULL REFERENCES users (id),
    body       VARCHAR(500) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_comments_post ON comments (post_id, id);

CREATE TABLE follows (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    follower_id BIGINT NOT NULL REFERENCES users (id),
    followee_id BIGINT NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_follows UNIQUE (follower_id, followee_id)
);
CREATE INDEX idx_follows_followee ON follows (followee_id);

-- 방명록: 남의 방에 남기는 글
CREATE TABLE guestbook_entries (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_owner_id BIGINT       NOT NULL REFERENCES users (id),
    author_id     BIGINT       NOT NULL REFERENCES users (id),
    body          VARCHAR(300) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_guestbook_room ON guestbook_entries (room_owner_id, id);

-- 깃털: 방에 놀러가서 하루 한 번 남기는 흔적
CREATE TABLE feathers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_owner_id BIGINT NOT NULL REFERENCES users (id),
    visitor_id    BIGINT NOT NULL REFERENCES users (id),
    visit_date    DATE   NOT NULL,
    color         VARCHAR(7) NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_feathers_daily UNIQUE (room_owner_id, visitor_id, visit_date)
);
CREATE INDEX idx_feathers_room ON feathers (room_owner_id, id);
